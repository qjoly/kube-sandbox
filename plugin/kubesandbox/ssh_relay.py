"""Long-lived exec tunnel: an in-sandbox sshd exposed on a local TCP port.

This is the relay the Phase 0 needs. Hermes' ``ssh`` backend runs its *client* on the Hermes host, so
the sandbox's sshd must be reachable from the host: here, a local TCP listener accepts connections and
for each one opens a **persistent** WebSocket exec stream running ``nc 127.0.0.1 22`` in the pod, then
pumps bytes both ways. ``ssh -o ProxyCommand=…`` is unnecessary — a plain ``ssh root@127.0.0.1 -p <port>``
works.

sshd itself is started inside the sandbox (the ``dev`` template has no sshd): a one-shot exec runs
``setsid sshd …`` so it outlives that call, with a per-claim host key and an authorized key the caller
passes in. Keys never leave the sandbox except the *public* one being authorized.
"""

from __future__ import annotations

import base64
import logging
import os
import secrets
import shlex
import socket
import subprocess
import threading
import time

from .protocol import ApiError, KubeClient, PodTarget

log = logging.getLogger(__name__)

__all__ = ["SshRelay", "ensure_sshd", "read_client_key"]

SSHD_CONFIG = (
    "Port 22\n"
    "ListenAddress 127.0.0.1\n"
    "HostKey {host_key}\n"
    "AuthorizedKeysFile /root/.ssh/authorized_keys\n"
    "PermitRootLogin prohibit-password\n"
    "StrictModes no\n"
    "UsePAM no\n"
    "PasswordAuthentication no\n"
    "PubkeyAcceptedAlgorithms +ssh-ed25519,*\n"
    "HostKeyAlgorithms +ssh-ed25519,*\n"
    "Subsystem sftp internal-sftp\n"
)


def _exec(client: KubeClient, target: PodTarget, script: str, timeout: float = 60.0) -> tuple[bytes, int]:
    return client.exec_ws(target, ["bash", "-c", script], timeout=timeout)


def ensure_sshd(client: KubeClient, claim, *, key_dir: str = "/run/kubesandbox-sshd",
                sshd_bin: str = "/usr/sbin/sshd") -> str:
    """Install (if needed) and start sshd inside the sandbox, and return its *public* key.

    The keypair is generated by the sandbox's own ``ssh-keygen``: this host's ``cryptography`` emits
    ed25519 blobs the sandbox's sshd refuses to match against ``authorized_keys``, while a key it
    generated itself is always accepted. Idempotent: a running sshd is left alone and its key re-read.
    """
    target = PodTarget(claim.namespace, claim.sandbox, claim.container)
    probe = ("(exec 3<>/dev/tcp/127.0.0.1/22) 2>/dev/null && echo RUNNING || echo STOPPED")
    out, rc = _exec(client, target, probe)
    if b"RUNNING" not in out:
        _start_sshd(client, target, key_dir, sshd_bin)
    out, _ = _exec(client, target, f"cat {key_dir}/client.pub")
    return out.decode().strip()
def _start_sshd(client: KubeClient, target: PodTarget, key_dir: str, sshd_bin: str) -> None:
    script = (
        "set -e\n"
        "export DEBIAN_FRONTEND=noninteractive\n"
        "command -v sshd >/dev/null 2>&1 || { "
        "DEBIAN_FRONTEND=noninteractive apt-get update -qq; "
        "DEBIAN_FRONTEND=noninteractive apt-get install -y -qq openssh-server netcat-openbsd; "
        "} >/dev/null 2>&1\n"
        "command -v sshd >/dev/null 2>&1 || { echo NO-SSHD; exit 1; }\n"
        "mkdir -p /run/kubesandbox-sshd /run/sshd\n"
        f"mkdir -p {key_dir} /run/sshd /root/.ssh\n"
        f"[ -f {key_dir}/host ] || ssh-keygen -q -t ed25519 -N '' -f {key_dir}/host\n"
        f"[ -f {key_dir}/client ] || ssh-keygen -q -t ed25519 -N '' -f {key_dir}/client\n"
        f"cp {key_dir}/client.pub /root/.ssh/authorized_keys\n"
        "chmod 700 /root/.ssh && chmod 600 /root/.ssh/authorized_keys\n"
        f"printf {shlex.quote(SSHD_CONFIG.format(host_key=key_dir + '/host'))} > {key_dir}/sshd_config\n"
        "pkill -x sshd 2>/dev/null || true\n"
        f"setsid {sshd_bin} -f {key_dir}/sshd_config -E {key_dir}/sshd.log "
        "</dev/null >/dev/null 2>&1 &\n"
        "sleep 2\n"
        "(exec 3<>/dev/tcp/127.0.0.1/22) 2>/dev/null && echo LISTENING "
        f"|| {{ echo NO-LISTEN; tail -5 {key_dir}/sshd.log; }}"
    )
    out, rc = _exec(client, target, script, timeout=300)
    if rc != 0 or b"LISTENING" not in out:
        detail = (out or b"").decode(errors="replace")[-500:] or f"(exit {rc}, no output)"
        raise ApiError(0, f"sshd did not start in {target.pod}: {detail}")


class SshRelay:
    """A local TCP listener that forwards each connection to the sandbox's sshd over an exec stream."""

    def __init__(self, client: KubeClient, claim, *, host: str = "127.0.0.1", port: int = 0,
                 remote_host: str = "127.0.0.1", remote_port: int = 22):
        self.client = client
        self.claim = claim
        self.host = host
        self.requested_port = port
        self.remote = (remote_host, remote_port)
        self._sock: socket.socket | None = None
        self._threads: list[threading.Thread] = []
        self._stop = threading.Event()
        self.port = port

    # -- lifecycle ---------------------------------------------------------
    def start(self) -> int:
        self._sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        self._sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        self._sock.bind((self.host, self.requested_port))
        self._sock.listen(16)
        self._sock.settimeout(0.5)
        self.port = self._sock.getsockname()[1]
        threading.Thread(target=self._accept_loop, daemon=True, name="kubesandbox-ssh-relay").start()
        log.info("ssh relay on %s:%d -> %s exec nc %s:%d", self.host, self.port, self.claim.sandbox,
                 *self.remote)
        return self.port

    def stop(self) -> None:
        self._stop.set()
        if self._sock is not None:
            try:
                self._sock.close()
            except OSError:
                pass

    def __enter__(self):
        self.start()
        return self

    def __exit__(self, *exc):
        self.stop()

    # -- plumbing ----------------------------------------------------------
    def _accept_loop(self) -> None:
        while not self._stop.is_set():
            try:
                conn, _addr = self._sock.accept()
            except (OSError, socket.timeout):
                continue
            t = threading.Thread(target=self._serve, args=(conn,), daemon=True)
            self._threads.append(t)
            t.start()

    def _serve(self, conn: socket.socket) -> None:
        target = PodTarget(self.claim.namespace, self.claim.sandbox, self.claim.container)
        try:
            ws = self.client.exec_stream(target, ["nc", self.remote[0], str(self.remote[1])])
        except ApiError as exc:
            log.warning("relay: exec stream failed: %s", exc)
            conn.close()
            return
        try:
            up = threading.Thread(target=self._pump_local_to_ws, args=(conn, ws), daemon=True)
            up.start()
            while True:
                frame = ws.recv_channel(timeout=3600)
                if frame is None:
                    break
                channel, data = frame
                if channel in (1, 2) and data:
                    conn.sendall(data)
        except OSError:
            pass
        finally:
            try:
                ws.close()
            except Exception:
                pass
            try:
                conn.shutdown(socket.SHUT_RDWR)
            except OSError:
                pass
            conn.close()

    @staticmethod
    def _pump_local_to_ws(conn: socket.socket, ws) -> None:
        try:
            while True:
                data = conn.recv(65536)
                if not data:
                    break
                ws.send_stdin(data)
        except OSError:
            pass
        finally:
            try:
                ws.send_stdin_eof()
            except Exception:
                pass


def read_client_key(client: KubeClient, claim, key_dir: str = "/run/kubesandbox-sshd") -> bytes:
    """The relay keypair's private half, pulled out of the sandbox for the local ssh client."""
    out, _ = _exec(client, PodTarget(claim.namespace, claim.sandbox, claim.container),
                   f"cat {key_dir}/client")
    return out
